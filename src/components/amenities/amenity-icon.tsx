/** Usado só para comodidades que ainda não estão no catálogo. */
const FallbackIcon = CircleCheck;

/** Traço padrão dos ícones de comodidade (fino, como o restante do site). */
export const AMENITY_STROKE = 1.75;

export type AmenityIconProps = Omit<LucideProps, "ref"> & {
  /** Slug da comodidade (catálogo em src/lib/amenities.ts). */
  name: string;
};

/**
 * Ícone de uma comodidade: `<AmenityIcon name="wi-fi" size={24} />`.
 * Decorativo por padrão (aria-hidden); passe `aria-label` quando o ícone
 * aparecer sozinho, sem o nome ao lado.
 */
export function AmenityIcon({
  name,
  size = 24,
  strokeWidth = AMENITY_STROKE,
  "aria-label": ariaLabel,
  ...props
}: AmenityIconProps) {
  const Icon = amenityIcons[name] ?? FallbackIcon;
  return (
    <Icon
      size={size}
      strokeWidth={strokeWidth}
      focusable="false"
      {...(ariaLabel ? { "aria-label": ariaLabel, role: "img" } : { "aria-hidden": true })}
      {...props}
    />
  );
}
